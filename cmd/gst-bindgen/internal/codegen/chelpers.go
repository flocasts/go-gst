package codegen

import (
	"fmt"
	"sort"
	"strings"

	"github.com/go-gst/go-gst/cmd/gst-bindgen/internal/girparser"
)

// generateCHelpers generates the _gen_chelpers.go.h and _gen_chelpers.go.c files
// with C type-cast helper functions used by Instance() methods.
func generateCHelpers(ctx *PackageContext) error {
	ns := ctx.Namespace

	type castEntry struct {
		cType    string // e.g., "GstElement"
		funcName string // e.g., "toGstElement"
		macro    string // e.g., "GST_ELEMENT"
	}

	var entries []castEntry

	// Collect GObject classes.
	for _, cls := range ns.Classes {
		if ctx.Overrides.IsTypeSkipped(cls.Name) {
			continue
		}
		rt := ctx.Registry.LookupType(ctx.Package.Namespace + "." + cls.Name)
		if rt == nil {
			continue
		}
		if rt.Kind != girparser.TypeKindGObject {
			continue
		}
		cType := cls.CType
		if cType == "" {
			cType = "Gst" + cls.Name
		}
		macro := ctx.Overrides.GetCastMacro(cType)
		if macro == "" {
			macro = CTypeToCastMacro(cType)
		}
		entries = append(entries, castEntry{
			cType:    cType,
			funcName: "toGst" + cls.Name,
			macro:    macro,
		})
	}

	// Collect mini-object records.
	for _, rec := range ns.Records {
		if ctx.Overrides.IsTypeSkipped(rec.Name) {
			continue
		}
		rt := ctx.Registry.LookupType(ctx.Package.Namespace + "." + rec.Name)
		if rt == nil || rt.Kind != girparser.TypeKindMiniObject {
			continue
		}
		cType := rec.CType
		if cType == "" {
			cType = "Gst" + rec.Name
		}
		macro := ctx.Overrides.GetCastMacro(cType)
		if macro == "" {
			macro = CTypeToCastMacro(cType)
		}
		entries = append(entries, castEntry{
			cType:    cType,
			funcName: "toGst" + rec.Name,
			macro:    macro,
		})
	}

	if len(entries) == 0 {
		return nil
	}

	sort.Slice(entries, func(i, j int) bool {
		return entries[i].cType < entries[j].cType
	})

	// Generate header file.
	var hBuf strings.Builder
	guard := fmt.Sprintf("__GST_BINDGEN_%s_H__", strings.ToUpper(goPackageName(ctx.Package.GoPackage)))
	hBuf.WriteString(fmt.Sprintf("/* Code generated by gst-bindgen. DO NOT EDIT. */\n\n"))
	hBuf.WriteString(fmt.Sprintf("#ifndef %s\n#define %s\n\n", guard, guard))
	hBuf.WriteString("#include \"gst.go.h\"\n\n")

	for _, e := range entries {
		hBuf.WriteString(fmt.Sprintf("extern %-30s %s(void *p);\n", e.cType+" *", e.funcName))
	}

	hBuf.WriteString(fmt.Sprintf("\n#endif /* %s */\n", guard))

	hPath := ctx.genFilePath("_gen_chelpers.go.h")
	if err := writeFileIfChanged(hPath, hBuf.String()); err != nil {
		return err
	}

	// Generate C implementation file.
	var cBuf strings.Builder
	cBuf.WriteString("/* Code generated by gst-bindgen. DO NOT EDIT. */\n\n")
	cBuf.WriteString("#include \"_gen_chelpers.go.h\"\n\n")

	for _, e := range entries {
		cBuf.WriteString(fmt.Sprintf("%-30s %s(void *p) { return (%s(p)); }\n",
			e.cType+" *", e.funcName, e.macro))
	}

	cPath := ctx.genFilePath("_gen_chelpers.go.c")
	return writeFileIfChanged(cPath, cBuf.String())
}
